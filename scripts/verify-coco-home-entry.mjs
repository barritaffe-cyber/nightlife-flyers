import {chromium} from 'playwright';
import {expect} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
const browser=await chromium.launch({headless:true});const base=process.env.BASE_URL||'http://localhost:3000';
const out='/tmp/coco-home-entry';mkdirSync(out,{recursive:true});
const errors=[];let page;
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 await context.route('**/api/analytics/**',r=>r.fulfill({json:{ok:true}}));
 page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base,{waitUntil:'domcontentloaded',timeout:120000});
 assert.equal(new URL(page.url()).pathname,'/');
 await expect(page.getByRole('heading',{level:1})).toHaveAccessibleName('Flyers in Five.');
 await expect(page.getByRole('link',{name:'Browse templates',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Open saved design',exact:true})).toBeVisible();
 await page.screenshot({path:`${out}/home-desktop.png`});
 console.log('Home ready');
 await page.getByRole('link',{name:'Tell Coco about your event',exact:true}).first().click();
 await expect(page.getByRole('textbox',{name:'Event name',exact:true})).toBeVisible({timeout:120000});
 await page.goto(base,{waitUntil:'domcontentloaded'});
 console.log('Create flow passed');
 await page.getByRole('link',{name:'Browse templates',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Choose a template',exact:true})).toBeVisible({timeout:120000});
 await expect(page.getByRole('heading',{name:'App mode available.'})).toHaveCount(0);
 await page.goto(base,{waitUntil:'domcontentloaded'});
 console.log('Browse flow passed');
 await expect(page.getByRole('button',{name:'Open saved design',exact:true})).toBeEnabled();
 const chooserPromise=page.waitForEvent('filechooser');
 await page.getByRole('button',{name:'Open saved design',exact:true}).click();
 await (await chooserPromise).setFiles('public/generated-flyers/ycee-live.nflyer');
 await expect(page.getByText('YCEE',{exact:true}).first()).toBeVisible({timeout:120000});
 await expect(page.getByText('Preparing square canvas.',{exact:true})).toHaveCount(0,{timeout:120000});
 await page.screenshot({path:`${out}/reopened.png`});
 await page.goto(`${base}/landing?utm_source=fb`,{waitUntil:'domcontentloaded'});
 assert.equal(new URL(page.url()).pathname,'/');
 assert.equal(new URL(page.url()).searchParams.get('utm_source'),'fb');
 await expect(page.getByRole('heading',{level:1})).toHaveAccessibleName('Flyers in Five.');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:`${out}/home-mobile.png`,fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('PASS: root home, three entry actions, saved-file import, template browser, legacy redirect, mobile; no page errors.');
}catch(error){if(page){console.log('Failed URL:',page.url());console.log((await page.locator('body').innerText()).slice(0,2500));await page.screenshot({path:`${out}/failure.png`});}throw error;}finally{await browser.close();}
